/**
 * Seed function to overwrite / populate Firestore with verified IIT (BHU) rooms
 */
export async function seedVerifiedRoomsToFirestore(): Promise<void> {
  console.info('🌱 Seeding verified IIT (BHU) rooms to Firestore...');
  for (const room of verifiedIITBHURooms) {
    if (!room.id) continue;
    const docRef = doc(db, 'rooms', room.id);
    await setDoc(docRef, room, { merge: true });
  }
  console.info('✅ Successfully seeded verified rooms into Firestore!');
}
